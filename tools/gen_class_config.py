"""Render the Marine class config and localization from tests/data/class_trees.json.

Usage: python -I tools/gen_class_config.py

Writes:
  Astartes/Config/XComClassData.ini           (whole file)
  Astartes/Config/XComGameData.ini            (whole file: squaddie loadouts)
  Astartes/Localization/XComGame.int          (replaces the block between the CLASSES markers)

The JSON is the spec; this script is deterministic so the generated files can be reviewed in git diffs.
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SPEC = REPO / "tests" / "data" / "class_trees.json"
MOD = REPO / "Astartes"
CLASS_INI = MOD / "Config" / "XComClassData.ini"
GAMEDATA_INI = MOD / "Config" / "XComGameData.ini"
LOC = MOD / "Localization" / "XComGame.int"

BEGIN = "; === BEGIN GENERATED: CLASSES (tools/gen_class_config.py) ==="
END = "; === END GENERATED: CLASSES ==="

SLOT_ENUM = {"primary": "eInvSlot_PrimaryWeapon", "secondary": "eInvSlot_SecondaryWeapon", "psiamp": "eInvSlot_PsiAmp"}

# Stat growth per rank (ranks 1..7). Marines grow a little harder than XCOM soldiers; base stats
# will come from the Marine character template later.
STAT_PROGRESSION = [
    "(StatType=eStat_Offense,StatAmount=3), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Will,StatAmount=5), (StatType=eStat_CombatSims,StatAmount=1)",
    "(StatType=eStat_Offense,StatAmount=3), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
    "(StatType=eStat_Offense,StatAmount=3), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
    "(StatType=eStat_Offense,StatAmount=2), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Strength,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
    "(StatType=eStat_Offense,StatAmount=2), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
    "(StatType=eStat_Offense,StatAmount=1), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
    "(StatType=eStat_Offense,StatAmount=1), (StatType=eStat_HP,StatAmount=1), (StatType=eStat_Strength,StatAmount=1), (StatType=eStat_Will,StatAmount=3)",
]


def ability_entry(slot: dict) -> str:
    name = slot.get("standin") or slot["name"]
    if "slot" in slot:
        return f'(AbilityType=(AbilityName="{name}", ApplyToWeaponSlot={SLOT_ENUM[slot["slot"]]}))'
    return f'(AbilityType=(AbilityName="{name}"))'


def render_class(class_name: str, c: dict) -> str:
    out = [f"[{class_name} X2SoldierClassTemplate]"]
    out += [
        "+bMultiplayerOnly=0",
        "+ClassPoints=4",
        f'+IconImage="{c["icon"]}"',
        "+NumInForcedDeck=1",
        "+NumInDeck=4",
        "+KillAssistsPerKill=4",
        f'+SquaddieLoadout="Squaddie{class_name}"',
    ]
    for slot_type, weapon_type in c["weapons"]:
        out.append(f'+AllowedWeapons=(SlotType={slot_type}, WeaponType="{weapon_type}")')
    out += [
        '+AllowedArmors="soldier"',
        "+bAllowAWCAbilities=1",
        "+bHasClassMovie=false",
        "+bCanHaveBonds=true",
        "+BaseAbilityPointsPerPromotion=3",
    ]
    for rank_index, rank in enumerate(c["ranks"]):
        slots = ", \\\\\n\t\t\t\t".join(ability_entry(s) for s in rank)
        out.append(f"+SoldierRanks=(AbilitySlots=({slots}), \\\\\n\t\t\t\taStatProgression=({STAT_PROGRESSION[rank_index]}))")
    return "\n".join(out) + "\n"


def render_class_ini(spec: dict) -> str:
    parts = [
        "; GENERATED by tools/gen_class_config.py from tests/data/class_trees.json - do not hand-edit.",
        "",
        "[XComGame.X2SoldierClass_DefaultClasses]",
    ]
    parts += [f'-SoldierClasses="{name}"' for name in spec.get("remove_from_deck", [])]
    parts += [f'+SoldierClasses="{name}"' for name in spec["classes"]]
    parts.append("")
    for name, c in spec["classes"].items():
        parts.append(render_class(name, c))
    return "\n".join(parts)


def render_gamedata_ini(spec: dict) -> str:
    parts = [
        "; GENERATED by tools/gen_class_config.py from tests/data/class_trees.json - do not hand-edit.",
        "",
        "[XComGame.X2ItemTemplateManager]",
    ]
    for name, c in spec["classes"].items():
        items = ", ".join(f'Items[{i}]=(Item="{item}")' for i, item in enumerate(c["loadout"]))
        parts.append(f'+Loadouts=(LoadoutName="Squaddie{name}", {items})')
    for lo in spec.get("extra_loadouts", []):
        items = ", ".join(f'Items[{i}]=(Item="{item}")' for i, item in enumerate(lo["items"]))
        parts.append(f'+Loadouts=(LoadoutName="{lo["name"]}", {items})')
    for lo in spec.get("loadout_overrides", []):
        removed = ", ".join(f'Items[{i}]=(Item="{item}")' for i, item in enumerate(lo["remove"]))
        items = ", ".join(f'Items[{i}]=(Item="{item}")' for i, item in enumerate(lo["items"]))
        parts.append(f'-Loadouts=(LoadoutName="{lo["name"]}", {removed})')
        parts.append(f'+Loadouts=(LoadoutName="{lo["name"]}", {items})')
    return "\n".join(parts) + "\n"


def render_loc_block(spec: dict) -> str:
    out = [BEGIN]
    for name, c in spec["classes"].items():
        ranks = spec["rank_names"][c["rank_set"]]
        shorts = spec["short_names"][c["rank_set"]]
        out.append(f"[{name} X2SoldierClassTemplate]")
        out.append(f'DisplayName="{c["display_name"]}"')
        out.append(f'ClassSummary="{c["summary"]}"')
        out.append(f'LeftAbilityTreeTitle="{c["columns"][0]}"')
        out.append(f'RightAbilityTreeTitle="{c["columns"][1]}"')
        for i, title in enumerate(c["columns"]):
            out.append(f'AbilityTreeTitles[{i}]="{title}"')
        out.append(f'AbilityTreeTitles[{len(c["columns"])}]="Chapter"')
        for i, rank in enumerate(ranks):
            out.append(f'RankNames[{i}]="{rank}"')
        for i, short in enumerate(shorts):
            out.append(f'ShortNames[{i}]="{short}"')
        out.append("")
    out.append(END)
    return "\n".join(out)


def splice_loc(existing: str, block: str) -> str:
    if BEGIN in existing and END in existing:
        head = existing[: existing.index(BEGIN)]
        tail = existing[existing.index(END) + len(END):]
        return head + block + tail
    return existing.rstrip("\n") + "\n\n" + block + "\n"


def main() -> None:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    CLASS_INI.write_text(render_class_ini(spec), encoding="utf-8")
    GAMEDATA_INI.write_text(render_gamedata_ini(spec), encoding="utf-8")
    LOC.write_text(splice_loc(LOC.read_text(encoding="utf-8-sig"), render_loc_block(spec)), encoding="utf-8")
    print(f"wrote {CLASS_INI.name}, {GAMEDATA_INI.name}, {LOC.name} for {len(spec['classes'])} classes")


if __name__ == "__main__":
    main()
