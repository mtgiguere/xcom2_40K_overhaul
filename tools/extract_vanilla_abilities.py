"""Regenerate tests/data/vanilla_abilities.txt from the WotC SDK source.

Usage: python -I tools/extract_vanilla_abilities.py ["<SDK path>"]

The list is what the config validator uses to decide whether an ability name referenced in our
class trees exists in the base game (plus Alien Hunters and Shen's Last Gift).
"""
from __future__ import annotations

import codecs
import re
import sys
from pathlib import Path

DEFAULT_SDK = Path(r"C:/Program Files (x86)/Steam/steamapps/common/XCOM 2 War of the Chosen SDK")
PACKAGES = ("XComGame", "DLC_2", "DLC_3")

PATTERNS = [
    re.compile(r"CreateTemplate\s*\(\s*class'X2AbilityTemplate'\s*,\s*'(\w+)'"),
    re.compile(r"\bPurePassive\s*\(\s*'(\w+)'"),
    re.compile(r"\bPURE_PASSIVE\s*\(\s*'(\w+)'"),
    re.compile(r"CREATE_X2ABILITY_TEMPLATE\s*\(\s*\w+\s*,\s*'(\w+)'"),
    re.compile(r"\bTemplateName\s*=\s*'(\w+)'\s*\)"),          # function Foo(name TemplateName = 'Foo')
    re.compile(r"Template Overrides '(\w+)'"),                   # autogenerated marker comments
    re.compile(r"\.SetTemplateName\s*\(\s*'(\w+)'"),
    re.compile(r"(?:TemplateName|AbilityName)\s*=\s*'(\w+)'"),   # default params: KillZone(name AbilityName='KillZone', ...)
    re.compile(r"Templates\.AddItem\(\s*\w+\s*\(\s*'(\w+)'"),      # Templates.AddItem(RunAndGunAbility('RunAndGun'))
]
LOC_HEADER = re.compile(r"^\[(\w+) X2AbilityTemplate\]", re.M)


def extract(sdk: Path) -> set[str]:
    names: set[str] = set()
    for pkg in PACKAGES:
        for f in (sdk / "Development" / "SrcOrig" / pkg / "Classes").glob("*.uc"):
            raw = f.read_bytes()
            enc = "utf-16" if raw[:2] in (codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE) else "utf-8"
            text = raw.decode(enc, errors="replace")
            for pat in PATTERNS:
                names.update(pat.findall(text))
    # Localization headers are the most reliable list: every ability with a display name has one.
    for loc in (sdk / "XComGame" / "Localization" / "INT").glob("*.int"):
        raw = loc.read_bytes()
        enc = "utf-16" if raw[:2] in (codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE) else "utf-8"
        names.update(LOC_HEADER.findall(raw.decode(enc, errors="replace")))
    for pkg in ("DLC_2", "DLC_3"):
        for loc in (sdk / "XComGame" / "DLC" / pkg / "Localization" / "INT").glob("*.int"):
            raw = loc.read_bytes()
            enc = "utf-16" if raw[:2] in (codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE) else "utf-8"
            names.update(LOC_HEADER.findall(raw.decode(enc, errors="replace")))
    return names


def main() -> None:
    sdk = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SDK
    names = extract(sdk)
    out = Path(__file__).resolve().parent.parent / "tests" / "data" / "vanilla_abilities.txt"
    out.write_text("\n".join(sorted(names)) + "\n", encoding="utf-8")
    print(f"{len(names)} ability template names -> {out}")


if __name__ == "__main__":
    main()
